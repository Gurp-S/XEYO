function scrapeExportedNames(regionLines) {
	const names = [];
	for (const line of regionLines) {
		let m = line.match(/^export (?:async )?(?:function|const|class|let|var) (\w+)/);
		if (m) {
			names.push({name: m[1], isType: false});
			continue;
		}
		m = line.match(/^export (?:type|interface) (\w+)/);
		if (m) names.push({name: m[1], isType: true});
	}
	return names;
}
function topLevelDecls(regionLines) {
	const out = [];
	const seen = new Set();
	const re = /^(?:export )?(?:async )?(function\*?|const|let|class|type|interface|enum)\s+(\w+)/gm;
	const text = stripComments(regionLines.join('\n'));
	let m;
	while ((m = re.exec(text))) {
		const kind = m[1];
		const name = m[2];
		if (seen.has(name)) continue;
		seen.add(name);
		out.push({name, isType: kind === 'type' || kind === 'interface'});
	}
	return out;
}
function facadeBodyText(out, importIdx) {
	// body = all lines except import blocks and re-export statement lines
	return stripComments(
		out
			.filter((_, i) => !importIdx.has(i) && !/^(export )?(type )?\{.*\} from /.test(out[i]))
			.join('\n'),
	);
}


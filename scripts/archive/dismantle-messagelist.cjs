// --- import block parsing (same as store scheduler) --------------------------

function parseImportBlocks(lines) {
	const blocks = [];
	let i = 0;
	while (i < lines.length) {
		const line = lines[i];
		let m = line.match(/^import type \{(.*)\} from '([^']+)';$/);
		if (m) {
			blocks.push({module: m[2], single: true, allType: true, lineIdx: [i], items: m[1].split(',').filter(s => s.trim()).map(s => ({name: s.trim().replace(/^type\s+/, ''), local: s.trim().replace(/^type\s+/, ''), isType: true, raw: null}))});
			i++;
			continue;
		}
		m = line.match(/^import \{(.*)\} from '([^']+)';$/);
		if (m) {
			blocks.push({module: m[2], single: true, allType: false, lineIdx: [i], items: m[1].split(',').filter(s => s.trim()).map(s => {
				const t = s.trim();
				const isType = /^type\s/.test(t);
				const name = t.replace(/^type\s+/, '');
				const am = name.match(/^([\w$]+)\s+as\s+([\w$]+)$/);
				return {name: am ? am[1] : name, local: am ? am[2] : name, isType, raw: null};
			})});
			i++;
			continue;
		}
		if (/^import \{$/.test(line) || /^import type \{$/.test(line)) {
			const start = i;
			const allType = /^import type \{$/.test(line);
			const items = [];
			let j = i + 1;
			let module = null;
			while (j < lines.length) {
				const mm = lines[j].match(/^\} from '([^']+)';$/);
				if (mm) {
					module = mm[1];
					j++;
					break;
				}
				const it = lines[j].match(/^\t?(type )?([\w$]+)(?:\s+as\s+([\w$]+))?,?\s*$/);
				if (it) {
					items.push({name: it[2], local: it[3] || it[2], isType: allType || !!it[1], raw: lines[j]});
				}
				j++;
			}
			if (module) blocks.push({module, single: false, allType, lineIdx: range(start, j), items});
			i = j;
			continue;
		}
		i++;
	}
	return blocks;
}
function range(a, b) {
	const out = [];
	for (let k = a; k < b; k++) out.push(k);
	return out;
}
const W = 'A-Za-z0-9_$';
function symbolUsed(bodyText, local, isType) {
	// word boundary without backslash-b: not adjacent to an identifier char;
	// value usage must also not be a member access (`.local`) or a key (`local:`)
	const re = new RegExp(
		'(^|[^' + W + '.])' + local + '(?!\\s*:)($|[^' + W + '])',
		'g',
	);
	const occ = bodyText.match(re);
	return !!occ && occ.length > 0;
}
const emitItem = it => (it.local !== it.name ? `${it.name} as ${it.local}` : it.local);

function siblingModules(spec) {
	// already-extracted siblings (same group) that this spec may import from
	const grp = spec.group || 'ml';
	const ids = ORDER.filter(id => (SPECS[id].group || 'ml') === grp);
	const idx = ids.indexOf(spec.id);
	const out = [];
	for (let k = 0; k < idx; k++) {
		const s = SPECS[ids[k]];
		const sMeta = loadMeta(s);
		const raw = sMeta.publicNames || (s.exports || []);
		// normalize to plain name strings
		const names = raw.map(n => (typeof n === 'string' ? n : n.name || n)).filter(Boolean);
		out.push({module: `./${path.basename(s.out).replace(/\.tsx?$/, '')}`, names});
	}
	return out;
}

// --- region location ---------------------------------------------------------

function locateRegions(lines, spec) {
	const out = [];
	let cursor = 0;
	for (const r of spec.regions) {
		let start = -1;
		for (let i = cursor; i < lines.length; i++) {
			if (r.start.test(lines[i])) {
				start = i;
				break;
			}
		}
		if (start < 0) fail(`anchor not found: start (${r.start})`);
		let end = -1;
		if (r.end) {
			for (let i = start + 1; i < lines.length; i++) {
				if (r.end.test(lines[i])) {
					end = i;
					break;
				}
			}
			if (end < 0) fail(`anchor not found: end (${r.end})`);
		} else {
			end = lines.length;
		}
		let region = lines.slice(start, end);
		while (region.length && region[region.length - 1].trim() === '') region.pop();
		const exportNames = spec.exports || scrapeExportedNames(region).map(n => n.name);
		for (const name of exportNames) {
			const declRe = new RegExp(`^(export )?(async )?(function\\*?|const|let|class|type|interface|enum) ${name}\\b`);
			if (!region.some(l => declRe.test(l))) {
				fail(`region sanity: export decl '${name}' not found`);
			}
		}
		out.push({start, end, region});
		cursor = end;
	}
	return out;
}

// --- builders ----------------------------------------------------------------

function prefixExports(regionLines, exports) {
	const out = [...regionLines];
	for (const name of exports) {
		const declRe = new RegExp(`^(export )?(async )?(function\\*?|const|let|class|type|interface|enum) ${name}\\b`);
		let hits = 0;
		for (let i = 0; i < out.length; i++) {
			if (declRe.test(out[i])) {
				if (!/^export /.test(out[i])) out[i] = `export ${out[i]}`;
				hits++;
			}
		}
		if (hits !== 1) fail(`export prefix: '${name}' matched ${hits} decl lines`);
	}
	return out;
}

function buildModule(spec, regions, srcLines, nl) {
	const regionLinesFlat = [];
	regions.forEach((r, i) => {
		if (i > 0) regionLinesFlat.push('');
		regionLinesFlat.push(...r.region);
	});
	const decls = topLevelDecls(regionLinesFlat);
	const autoNames = spec.exports || scrapeExportedNames(regionLinesFlat).map(n => n.name);
	let moved;
	if (spec.reExport === 'from') {
		// every decl must be exported from the chunk (facade re-exports / binds them)
		moved = prefixExports(regionLinesFlat, decls.map(n => n.name));
	} else if (spec.exports) {
		moved = prefixExports(regionLinesFlat, spec.exports);
	} else {
		moved = regionLinesFlat;
	}
	const stripped = stripComments(regionLinesFlat.join('\n'));

	const parsed = parseImportBlocks(srcLines);
	// source import paths are relative to the original file's dir; new files live
	// one level deeper — rewrite and merge duplicates.
	const prefix = spec.importPrefix || './messageList/';
	const relRewrite = m => {
		if (m.startsWith(prefix)) return './' + m.slice(prefix.length);
		if (m.startsWith('./')) return '../' + m.slice(2);
		return m;
	};
	const merged = new Map();
	for (const block of parsed) {
		const items = block.items.filter(it => symbolUsed(stripped, it.local, it.isType));
		if (!items.length) continue;
		const key = relRewrite(block.module);
		const entry = merged.get(key) || {module: key, items: []};
		const seen = new Set(entry.items.map(i => i.local + '|' + i.isType));
		for (const it of items) {
			if (!seen.has(it.local + '|' + it.isType)) {
				entry.items.push(it);
				seen.add(it.local + '|' + it.isType);
			}
		}
		merged.set(key, entry);
	}
	const usedByModule = [...merged.values()];
	const usedSiblings = siblingModules(spec)
		.map(s => ({...s, names: s.names.filter(n => symbolUsed(stripped, n, false))}))
		.filter(s => s.names.length)
		.map(s => ({
			...s,
			names: s.names.filter(n => {
				const cov = merged.get(s.module);
				return !cov || !cov.items.some(it => it.local === n);
			}),
		}))
		.filter(s => s.names.length);

	// orphans = monolith top-level symbols referenced by the moved region that
	// neither the chunk defines nor imports — they stay in the facade and must be
	// re-imported (ES live binding; functions hoist so no TDZ at call time).
	const ownNames = new Set(decls.map(d => d.name));
	const importedNames = new Set();
	usedByModule.forEach(({items}) => items.forEach(i => importedNames.add(i.local)));
	usedSiblings.forEach(s => s.names.forEach(n => importedNames.add(n)));
	const monolithTop = topLevelDecls(srcLines).map(d => d.name);
	const facadeRel = {api: '../api', ta: '../toolActivity', ph: '../../preStoreHelpers'}[spec.group];
	const orphanNames = [];
	if (facadeRel) {
		for (const name of monolithTop) {
			if (ownNames.has(name) || importedNames.has(name)) continue;
			if (symbolUsed(stripped, name, false)) orphanNames.push(name);
		}
	}

	const out = [
		'/**',
		` * AUTO-GENERATED by dismantle-messagelist.cjs (spec ${spec.id}: ${spec.title}).`,
		' * Blocks moved verbatim from components/MessageList.tsx. Behavior unchanged.',
		' */',
	];
	for (const {module, items} of usedByModule) {
		out.push('import {');
		for (const v of items.filter(it => !it.isType).map(emitItem).sort()) out.push(`\t${v},`);
		for (const t of items.filter(it => it.isType).map(emitItem).sort()) out.push(`\ttype ${t},`);
		out.push(`} from '${module}';`);
	}
	for (const s of usedSiblings) {
		out.push(`import {${s.names.filter(n => symbolUsed(stripped, n, false)).join(', ')}} from '${s.module}';`);
	}
	if (orphanNames.length) {
		out.push(`import {${orphanNames.sort().join(', ')}} from '${facadeRel}';`);
	}
	if (spec.manifest) {
		const vals = decls.filter(n => !n.isType).map(n => n.name).sort();
		const typs = decls.filter(n => n.isType).map(n => n.name).sort();
		if (vals.length) moved.push(`export {${vals.join(', ')}};`);
		if (typs.length) moved.push(`export type {${typs.join(', ')}};`);
	}
	out.push('', ...moved, '');
	return {src: out.join(nl), usedByModule, usedSiblings};
}

function patchSource(spec, lines, regions, nl) {
	// remove regions; record added-import lines and trimmed blocks
	let out = [];
	let cursor = 0;
	regions.forEach(r => {
		out.push(...lines.slice(cursor, r.start));
		cursor = r.end;
	});
	out.push(...lines.slice(cursor));

	// facade internals referenced by moved regions must become importable by the
	// chunk: add `export ` to any such top-level decl that is currently unexported.
	// (Chunk imports them from facadeRel; export surface only grows.)
	const exportReverts = [];
	if (!spec.exportInternalsDisabled) {
		const movedText = stripComments(regions.map(r => r.region.join('\n')).join('\n'));
		const monolithTop = topLevelDecls(lines);
		const monolithExported = new Set(scrapeExportedNames(lines).map(n => n.name));
		const exportTargets = [];
		for (const d of monolithTop) {
			if (monolithExported.has(d.name)) continue;
			if (symbolUsed(movedText, d.name, d.isType)) exportTargets.push(d.name);
		}
		if (exportTargets.length) {
			const targetSet = new Set(exportTargets);
			out = out.map(l => {
				const m = l.match(/^(?:export )?(async )?(function\*?|const|let|class|type|interface|enum)\s+(\w+)\b/);
				if (m && targetSet.has(m[3]) && !/^export /.test(l)) {
					exportReverts.push({exportedLine: 'export ' + l, originalLine: l});
					return 'export ' + l;
				}
				return l;
			});
		}
	}

	const blockEdits = [];
	for (;;) {
		const parsed = parseImportBlocks(out);
		const importIdx = new Set();
		for (const b of parsed) for (const i of b.lineIdx) importIdx.add(i);
		const bodyText = facadeBodyText(out, importIdx);
		let edited = false;
		for (const block of parsed) {
			const kept = block.items.filter(it => symbolUsed(bodyText, it.local, it.isType));
			if (kept.length === block.items.length) continue;
			const originalLines = block.lineIdx.map(i => out[i]);
			const blockIsType = block.allType || block.items.every(it => it.isType);
			let newLines;
			if (block.single) {
				const emit = it => {
					const base = it.local !== it.name ? `${it.name} as ${it.local}` : it.local;
					// `import type {A}` already marks the whole set as types
					return blockIsType ? base : (it.isType ? `type ${base}` : base);
				};
				const prefix = blockIsType ? 'import type ' : 'import ';
				newLines = [`${prefix}{${kept.map(emit).join(', ')}} from '${block.module}';`];
			} else {
				newLines = [block.allType ? 'import type {' : 'import {'];
				for (const it of kept) newLines.push(it.raw);
				newLines.push(`} from '${block.module}';`);
			}
			out.splice(block.lineIdx[0], block.lineIdx.length, ...newLines);
			blockEdits.push({module: block.module, originalLines, rebuiltLines: newLines});
			edited = true;
			break;
		}
		if (!edited) break;
	}

	// re-export / re-import moved public names so the facade's external API
	// (inline exports or tail export manifest) stays intact.
	const addedImports = [];
	const modName = path.basename(spec.out).replace(/\.tsx?$/, '');
	let publicNames = null;
	if (spec.reExport === 'from' || spec.manifest) {
		if (spec.manifest) {
			// names in the facade's tail export manifest declared in moved regions
			const manifestNames = [];
			const typeNames = new Set();
			for (const l of out) {
				let m = l.match(/^export \{(.*)\};$/);
				if (m) for (const p of m[1].split(',')) if (p.trim()) manifestNames.push({name: p.trim(), isType: false});
				m = l.match(/^export type \{(.*)\};$/);
				if (m) for (const p of m[1].split(',')) {
					const t = p.trim();
					if (t) {
						manifestNames.push({name: t, isType: true});
						typeNames.add(t);
					}
				}
			}
			const regionText = stripComments(regions.map(r => r.region.join('\n')).join('\n'));
			publicNames = manifestNames.filter(({name}) =>
				new RegExp(`^(?:async )?(?:function|const|let|class) ${name}\\b|^(?:type|interface) ${name}\\b`, 'm').test(regionText),
			);
		} else {
			// all top-level decls become module-public: remaining facade body and
			// later sibling chunks may call internals (export surface only grows)
			publicNames = regions.flatMap(r => topLevelDecls(r.region));
		}
		const modPath = `${spec.importPrefix || './messageList/'}${modName}`;
		const values = publicNames.filter(n => !n.isType).map(n => n.name).sort();
		const types = publicNames.filter(n => n.isType).map(n => n.name).sort();
		const kw = spec.reExport === 'from' ? 'export' : 'import';
		const lines2 = [];
		if (kw === 'export') {
			// remaining facade body may still CALL moved symbols: bind the used ones.
			// Exclude import/export statement lines (re-exports don't need a binding).
			const parsedB = parseImportBlocks(out);
			const bodyIdx = new Set();
			for (const b of parsedB) for (const i of b.lineIdx) bodyIdx.add(i);
			const bodyText = facadeBodyText(out, bodyIdx);
			const usedV = values.filter(n => symbolUsed(bodyText, n, false));
			const usedT = types.filter(n => symbolUsed(bodyText, n, true));
			if (usedV.length) lines2.push(`import {${usedV.join(', ')}} from '${modPath}';`);
			if (usedT.length) lines2.push(`import type {${usedT.join(', ')}} from '${modPath}';`);
		}
		if (values.length) lines2.push(`${kw} {${values.join(', ')}} from '${modPath}';`);
		if (types.length) lines2.push(`${kw === 'export' ? 'export type' : 'import type'} {${types.join(', ')}} from '${modPath}';`);
		if (lines2.length) {
			addedImports.push(...lines2);
			const parsed2 = parseImportBlocks(out);
			let lastClose = -1;
			for (const b of parsed2) lastClose = Math.max(lastClose, b.lineIdx[b.lineIdx.length - 1]);
			if (lastClose < 0) fail('source: no import blocks found');
			out.splice(lastClose + 1, 0, ...lines2);
		}
	} else {
		const bodyText = stripComments(out.join('\n'));
		const needSelf = spec.exports.filter(n => symbolUsed(bodyText, n, false));
		if (needSelf.length) {
			const imp = `import {${needSelf.join(', ')}} from './messageList/${modName}';`;
			addedImports.push(imp);
			const parsed2 = parseImportBlocks(out);
			let lastClose = -1;
			for (const b of parsed2) lastClose = Math.max(lastClose, b.lineIdx[b.lineIdx.length - 1]);
			if (lastClose < 0) fail('source: no import blocks found');
			out.splice(lastClose + 1, 0, imp);
		}
	}
	return {src: out.join(nl), blockEdits, addedImports, publicNames, exportReverts};
}


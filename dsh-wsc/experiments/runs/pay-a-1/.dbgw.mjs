import { mkdtemp, mkdir, writeFile, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { watch } from "node:fs";
import { startWatch } from "./lib/watch.js";
import { parseArgs } from "./lib/build.js";
const root = await mkdtemp(path.join(tmpdir(), "dbgw-"));
await mkdir(path.join(root, "src"), { recursive: true });
await writeFile(path.join(root, "src/a.txt"), "a");
const opts = parseArgs(["--src","src","--out","out","--manifest","build-manifest.json"]);
const srcDir = path.join(root, "src"), outDir = path.join(root, "out");
const raw = watch(srcDir, { recursive: true }, (e, f) => console.log("EVENT", e, JSON.stringify(f && f.toString())));
const reports = [];
const w = startWatch(opts, { cwd: root, debounceMs: 20, onReport: (r) => { reports.push(r); console.log("REPORT", reports.length, JSON.stringify(r.built)); } });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
await sleep(300);
console.log("--- after initial:", reports.length);
await writeFile(path.join(root, "src/a.txt"), "b");
await sleep(300);
console.log("--- after change:", reports.length);
raw.close(); w.close();

import { mkdtemp, mkdir, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { watch } from "node:fs";
import { startWatch } from "./lib/watch.js";
import { parseArgs } from "./lib/build.js";
const root = await mkdtemp(path.join(tmpdir(), "dbgw2-"));
await mkdir(path.join(root, "src"), { recursive: true });
await writeFile(path.join(root, "src/w.js"), "export const w = 1;\n");
const opts = parseArgs(["--src","src","--out","src/out","--manifest","build-manifest.json"]);
const srcDir = path.join(root, "src");
const raw = watch(srcDir, { recursive: true }, (e, f) => console.log("EVENT", e, JSON.stringify(f && f.toString())));
const reports = [];
const w = startWatch(opts, { cwd: root, debounceMs: 20, onReport: (r) => { reports.push(r); console.log("REPORT", reports.length, JSON.stringify(r.built)); } });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
await sleep(400);
console.log("--- after initial:", reports.length);
await writeFile(path.join(root, "src/w.js"), "export const w = 2;\n");
await sleep(400);
console.log("--- after change:", reports.length);
raw.close(); w.close();

"""Structural cache scenarios for offline replay, never provider usage.

The previous input and the previous input plus its generated response are
different possible persisted prefixes. Keep both estimates: availability,
tokenizer boundaries and provider persistence are not inferred from strings.
"""
from dataclasses import dataclass

from synaptic.textutil import node_token_len


def shared_tokens(left: str, right: str) -> int:
    low, high = 0, min(len(left), len(right))
    while low < high:
        middle = (low + high + 1) // 2
        if left[:middle] == right[:middle]:
            low = middle
        else:
            high = middle - 1
    return min(node_token_len(right), node_token_len(left[:low]))


@dataclass(frozen=True)
class PrefixEstimate:
    tokens: int
    input_hit: int
    response_hit: int

    @property
    def input_miss(self) -> int:
        return self.tokens - self.input_hit

    @property
    def response_miss(self) -> int:
        return self.tokens - self.response_hit


def estimate(current: str, *, previous: str | None,
             response_prefix: str | None = None) -> PrefixEstimate:
    """Report input-only and optimistic response-prefix scenarios separately."""
    total = node_token_len(current)
    if previous is None:
        return PrefixEstimate(total, 0, 0)
    input_hit = shared_tokens(previous, current)
    response_hit = input_hit if response_prefix is None else max(
        input_hit, shared_tokens(response_prefix, current)
    )
    return PrefixEstimate(total, input_hit, response_hit)


def leading_assistant_outputs(messages: list[dict], previous_end: int) -> list[dict]:
    """Only contiguous generated output before the next external input.

    Tool results, user input and injected state terminate this prefix; their
    contents were not generated by the preceding model response.
    """
    if not 0 <= previous_end <= len(messages):
        return []
    output = []
    for message in messages[previous_end:]:
        if message.get('role') != 'assistant':
            break
        output.append(message)
    return output

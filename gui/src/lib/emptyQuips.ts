let lastIndex = -1;

/** 选取一条俏皮话；尽可能避免与上一条重复。 */
export function pickEmptyQuip(rng = Math.random): string {
	const n: number = EMPTY_QUIPS.length;
	if (n === 0) {
		return '';
	}
	if (n === 1) {
		return EMPTY_QUIPS[0]!;
	}
	let i = Math.floor(rng() * n) % n;
	if (i === lastIndex) {
		i = (i + 1 + Math.floor(rng() * (n - 1))) % n;
	}
	lastIndex = i;
	return EMPTY_QUIPS[i]!;
}

/** 测试辅助 — 重置防重复状态。 */
export function resetEmptyQuipState(): void {
	lastIndex = -1;
}
